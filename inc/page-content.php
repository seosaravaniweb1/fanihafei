/**
 * کمک‌کننده: یک مرحله‌ی تصویری.
 *
 * برخلاف fs_blk_bigstep که شماره را با counter در CSS می‌کشد، اینجا شماره
 * داخل خود تصویر است؛ پس شماره‌ی CSS را نمی‌گذاریم تا دو بار دیده نشود.
 *
 * تصویر عمداً بدون src ساخته می‌شود: فایل باید در کتابخانه‌ی رسانه‌ی همان سایت
 * آپلود شود، نه داخل پوشه‌ی قالب. در ویرایشگر روی جای خالی کلیک کنید و تصویر
 * را انتخاب کنید.
 *
 * @param string $title عنوان.
 * @param string $text  توضیح.
 * @param string $alt   متن جایگزین تصویر.
 * @return string
 */
function fs_blk_imgstep( $title, $text, $alt ) {
	return '<!-- wp:group {"className":"fs-steps3__item"} -->' . "\n" .
		'<div class="wp-block-group fs-steps3__item">' . "\n" .
		'<!-- wp:image {"sizeSlug":"full","className":"fs-steps3__img"} -->' . "\n" .
		'<figure class="wp-block-image size-full fs-steps3__img"><img alt="' . esc_attr( $alt ) . '"/></figure>' . "\n" .
		'<!-- /wp:image -->' . "\n\n" .
		'<!-- wp:heading {"level":3} -->' . "\n" . '<h3 class="wp-block-heading">' . $title . '</h3>' . "\n" . '<!-- /wp:heading -->' . "\n\n" .
		fs_blk_p( $text ) .
		'</div>' . "\n" . '<!-- /wp:group -->' . "\n\n";
}

