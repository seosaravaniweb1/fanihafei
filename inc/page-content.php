/**
 * کمک‌کننده: یک بخش با تیتر h2.
 *
 * @param string $title تیتر.
 * @return string
 */
function fs_blk_h2( $title ) {
	return '<!-- wp:heading -->' . "\n" . '<h2 class="wp-block-heading">' . $title . '</h2>' . "\n" . '<!-- /wp:heading -->' . "\n\n";
}

/**
 * کمک‌کننده: پاراگراف.
 *
 * @param string $text  متن.
 * @param string $class کلاس اختیاری.
 * @return string
 */
function fs_blk_p( $text, $class = '' ) {
	if ( $class ) {
		return '<!-- wp:paragraph {"className":"' . $class . '"} -->' . "\n" . '<p class="' . $class . '">' . $text . '</p>' . "\n" . '<!-- /wp:paragraph -->' . "\n\n";
	}

	return '<!-- wp:paragraph -->' . "\n" . '<p>' . $text . '</p>' . "\n" . '<!-- /wp:paragraph -->' . "\n\n";
}

/**
 * کمک‌کننده: فهرست تیک‌دار.
 *
 * @param string[] $items موارد.
 * @return string
 */
function fs_blk_list( $items ) {
	$out = '<!-- wp:list {"className":"is-style-fs-check"} -->' . "\n" . '<ul class="wp-block-list is-style-fs-check">' . "\n";

	foreach ( $items as $item ) {
		$out .= '<!-- wp:list-item -->' . "\n" . '<li>' . $item . '</li>' . "\n" . '<!-- /wp:list-item -->' . "\n";
	}

	return $out . '</ul>' . "\n" . '<!-- /wp:list -->' . "\n\n";
}

/**
 * کمک‌کننده: جعبه با سبک مشخص.
 *
 * @param string $style سبک (fs-card | fs-note | fs-warn | fs-steps).
 * @param string $inner بلوک‌های داخلی.
 * @return string
 */
function fs_blk_box( $style, $inner ) {
	return '<!-- wp:group {"className":"is-style-' . $style . '"} -->' . "\n" .
		'<div class="wp-block-group is-style-' . $style . '">' . "\n" . $inner .
		'</div>' . "\n" . '<!-- /wp:group -->' . "\n\n";
}

/**
 * کمک‌کننده: آکاردئون پرسش و پاسخ.
 *
 * @param string $q پرسش.
 * @param string $a پاسخ.
 * @return string
 */
function fs_blk_faq( $q, $a ) {
	return '<!-- wp:details {"className":"fs-acc"} -->' . "\n" .
		'<details class="wp-block-details fs-acc"><summary>' . $q . '</summary>' . "\n" .
		fs_blk_p( $a ) .
		'</details>' . "\n" . '<!-- /wp:details -->' . "\n\n";
}

