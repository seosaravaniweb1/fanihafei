/**
 * دریافت یک متن ثابت.
 *
 * @param string $key کلید متن.
 * @return string
 */
function fs_copy( $key ) {
	$copy = fs_data_copy();

	return isset( $copy[ $key ] ) ? $copy[ $key ] : '';
}
