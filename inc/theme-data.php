/**
 * نشانه‌های اعتماد زیر هیرو — متن ثابت رابط کاربری، از سفارشی‌سازی قابل تغییر.
 *
 * @return string[]
 */
function fs_data_trust() {
	$items = fs_get_trust_items();

	if ( $items ) {
		return apply_filters( 'fs_data_trust', $items );
	}

	return apply_filters(
		'fs_data_trust',
		array(
			'دانلود فوری بعد از پرداخت',
			'فایل‌های اصل و بدون واترمارک',
			'پیش‌نمایش رایگان قبل از خرید',
			'پشتیبانی و بازگشت وجه',
		)
	);
}

